"""Rehearse exact pending SQL in one rolled-back transaction on an EMPTY local *_test DB."""

import argparse
import hashlib
import json
import os
from pathlib import Path
from uuid import uuid4

import psycopg
from prepare_guest_migration_review import BASE, migration_sql
from sqlalchemy.engine import make_url
from sqlalchemy.exc import ArgumentError


def require_target(raw: str):
    try:
        target = make_url(raw)
    except (ArgumentError, TypeError):
        raise ValueError("Explicit loopback PostgreSQL *_test target required") from None
    if (target.drivername != "postgresql+psycopg" or target.host not in ("localhost", "127.0.0.1", "::1")
            or not (target.database or "").endswith("_test") or target.query):
        raise ValueError("Explicit loopback PostgreSQL *_test target required; connection overrides refused")
    return target


def transaction_body(sql: str) -> str:
    # Compare to independently regenerated bytes first. Strip only Alembic's exact outer scaffold;
    # dollar-quoted PL/pgSQL BEGIN/END blocks must never be rewritten by a broad regex.
    if not sql.startswith("BEGIN;\n") or not sql.rstrip().endswith("COMMIT;"):
        raise ValueError("Unexpected offline transaction scaffold")
    return sql.removeprefix("BEGIN;\n").rstrip().removesuffix("COMMIT;")


def verify(path: Path, raw: str) -> dict:
    target = require_target(raw)
    data = Path(path).read_bytes()
    expected = migration_sql().encode()
    if data != expected:
        raise ValueError("Pending SQL must exactly match the current offline migration bytes")
    baseline = transaction_body(migration_sql(f"base:{BASE}"))
    pending = transaction_body(data.decode())
    url = target.set(drivername="postgresql").render_as_string(hide_password=False)
    with psycopg.connect(url, autocommit=False) as db:
        try:
            if db.execute("select exists(select 1 from pg_namespace where nspname in ('moodprint','auth')) or exists(select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace where c.relkind in ('r','p','v','m','S','f') and n.nspname not like 'pg_%' and n.nspname not in ('information_schema','extensions'))").fetchone()[0]:
                raise ValueError("Verifier requires an empty local target")
            runtime = db.execute("select rolsuper,rolbypassrls,rolcreaterole,rolcreatedb,rolreplication,rolcanlogin from pg_roles where rolname='moodprint_runtime'").fetchone()
            if runtime and any(runtime):
                raise ValueError("Existing runtime role must be an unprivileged NOLOGIN group")
            db.execute("set local lock_timeout='5s'; set local statement_timeout='60s'")
            db.execute("create schema moodprint; create schema auth; create table auth.users(id uuid primary key, is_anonymous boolean not null, raw_user_meta_data jsonb not null default '{}', created_at timestamptz not null default now()); create table auth.sessions(id uuid primary key, user_id uuid references auth.users(id) on delete cascade)")
            for role in ("moodprint_runtime", "anon", "authenticated", "service_role"):
                if not db.execute("select 1 from pg_roles where rolname=%s", (role,)).fetchone():
                    db.execute(f"create role {role} nologin nosuperuser nobypassrls")
            db.execute(baseline, prepare=False)
            # Reproduce the separately reviewed backend-only baseline ACL (not an approval).
            db.execute("grant usage on schema moodprint to moodprint_runtime; grant select,insert,update,delete on all tables in schema moodprint to moodprint_runtime")
            db.execute(pending, prepare=False)
            assert db.execute("select version_num from moodprint.alembic_version").fetchone() == ("0018_app_feedback",)
            for table in ("app_feedback", "feedback_submission_receipts", "feedback_review_events", "guest_cleanup_jobs", "guest_cost_reservations"):
                for operation in ("SELECT", "INSERT", "UPDATE", "DELETE"):
                    assert db.execute("select has_table_privilege('moodprint_runtime',%s,%s)", (f"moodprint.{table}", operation)).fetchone()[0]
                    for role in ("anon", "authenticated", "service_role"):
                        assert not db.execute("select has_table_privilege(%s,%s,%s)", (role, f"moodprint.{table}", operation)).fetchone()[0]
            from uuid import UUID
            rows = []
            for guest in (False, True):
                uid, sid, provider = uuid4(), uuid4(), uuid4()
                db.execute("insert into auth.users(id,is_anonymous) values (%s,%s)", (uid, guest))
                db.execute("insert into auth.sessions(id,user_id) values (%s,%s)", (provider, uid))
                db.execute("insert into moodprint.users(id,auth_subject,alias,age_band,status,timezone,auth_version,data_version,profile_version,account_kind,guest_started_at,guest_expires_at) values (%s,%s,'synthetic','adult','active','Asia/Bangkok',1,1,0,%s,case when %s then now()-interval '3 hours' end,case when %s then now()-interval '1 hour' end)", (uid, uid, "guest" if guest else "registered", guest, guest))
                db.execute("insert into moodprint.auth_sessions(id,user_id,token_hash,csrf_hash,provider_session_id,revoked,auth_version,expires_at) values (%s,%s,%s,%s,%s,false,1,case when %s then now()-interval '1 hour' else now()+interval '1 hour' end)", (sid, uid, uuid4().hex * 2, uuid4().hex * 2, provider, guest))
                rows.append((sid, uid))
            db.execute("set local role moodprint_runtime")
            assert db.execute("select moodprint.is_provider_session_active(%s,%s)", rows[0]).fetchone()[0]
            assert not db.execute("select moodprint.is_provider_session_active(%s,%s)", rows[1]).fetchone()[0]
            assert not db.execute("select has_table_privilege(current_user,c.oid,'SELECT') from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='auth' and c.relname='users'").fetchone()[0]
            value = db.execute("insert into moodprint.app_feedback(id,rating,app_version,account_kind,disclosure_version) values (gen_random_uuid(),4,'synthetic-review','guest','feedback-v1') returning id").fetchone()[0]
            assert isinstance(value, UUID)
            db.execute("delete from moodprint.app_feedback where id=%s", (value,))
            db.execute("reset role")
        finally:
            db.rollback()
        assert not db.execute("select exists(select 1 from pg_namespace where nspname in ('moodprint','auth'))").fetchone()[0]
    return {"status": "PASS", "sha256": hashlib.sha256(data).hexdigest(), "ddlRolledBack": True, "remoteExecuted": False}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sql", type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(verify(args.sql, os.environ.get("TEST_DATABASE_URL", ""))))
