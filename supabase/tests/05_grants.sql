begin;
create extension if not exists pgtap with schema extensions;
set local search_path=public,extensions;
select no_plan();
select ok(not has_schema_privilege('anon',s,'USAGE'), 'anon cannot enter '||s) from unnest(array['app','app_private','agent_store']) s;
select ok(not has_table_privilege('moodprint_api','app.messages','SELECT'),'login role cannot directly read transcript');
select ok(not has_table_privilege('service_role','app.messages','SELECT'),'secret HTTP role cannot directly read transcript');
select ok(not has_table_privilege('authenticated','agent_store.agent_messages','SELECT'),'user role cannot read SDK replay');
select ok(not has_function_privilege('authenticated','app_private.reconcile_stale_runs(interval)','EXECUTE'),'user cannot reconcile across owners');
select ok(has_function_privilege('moodprint_api','app_private.reconcile_stale_runs(interval)','EXECUTE'),'only backend login can reconcile');
select ok(not rolbypassrls and not rolsuper and not rolinherit and not rolcreatedb and not rolcreaterole,'login role has no elevated attributes') from pg_roles where rolname='moodprint_api';
select ok(not inherit_option and set_option,'role membership permits explicit switching only') from pg_auth_members where member='moodprint_api'::regrole and roleid='authenticated'::regrole;
-- postgres is not SUPERUSER on Supabase. Temporary membership is test-local.
grant moodprint_api to postgres;
grant usage on schema extensions to moodprint_api;
set local role moodprint_api;
select throws_ok($$select content from app.messages$$,'42501',null,'direct content read fails for background login');
select lives_ok($$select app_private.reconcile_stale_runs(interval '2 minutes')$$,'narrow reconciler executes');
reset role;
select * from finish();
rollback;
