"""Typed inter-companion contracts (phase-2/03 §3). Backend-only except ``CollaborationSummary``.

Four kinds of information are kept apart on purpose:

1. facts retrieved from authorized data (``JournalExcerpt``) — never leave the specialist run;
2. summaries derived from those facts (``EnergyHint.energy``) — a closed enum, labelled as an
   estimate when shown to the primary companion;
3. suggestions generated by a companion (``TinyHabit.habit_text``, ``InterestActivity``) —
   labelled as a suggestion, never as something known about the user;
4. execution metadata (``ExecutionReceipt``) — content-free, the only basis of any UI line.
"""

import hashlib
import json
from datetime import date, datetime
from typing import Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, model_validator

from app.ai.proactive.output import ChallengeKind
from app.ai.schemas import CollaborationSummary  # noqa: F401 -- public DTO, re-exported
from app.contracts import BotId

Edge = Literal["nhip_energy_for_rure", "nhip_habit_for_may", "rure_activity_for_guong"]
RuleId = Literal["R1", "R2", "R3", "R4"]
InputSchema = Literal["energy-hint-in-v1", "tiny-habit-in-v1", "interest-activity-in-v1"]
Need = Literal["sleep", "stress", "focus", "energy"]
TimeOfDay = Literal["morning", "afternoon", "evening", "night"]
TimeBudget = Literal[5, 10, 15]
InterestTag = Literal[
    "drawing", "reading", "music", "cooking", "sport", "nature", "games", "writing", "languages",
    "technology",
]
HabitKind = Literal["breathing", "screen_break", "movement", "hydration", "wind_down", "planning"]
DenyReason = Literal[
    "ok", "feature_off", "edge_disabled", "journal_consent_off", "no_data", "daily_cap", "budget",
    "distress", "depth", "already_consulted", "ineligible_account", "time_budget", "capacity",
]
Status = Literal["authorized", "denied", "completed", "failed", "timeout", "cancelled", "discarded"]


class _Frozen(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class JournalExcerpt(_Frozen):
    """A retrieved fact. Sent only to the Nhịp specialist of ``nhip_energy_for_rure``."""

    entry_id: UUID
    revision: int = Field(ge=1)
    local_date: date
    mood: int = Field(ge=1, le=5)
    emotions: tuple[str, ...] = Field(default=(), max_length=6)
    factors: tuple[str, ...] = Field(default=(), max_length=6)
    excerpt: str = Field(max_length=600)
    excerpt_truncated: bool = False


_FIELDS: dict[str, set[str]] = {
    "energy-hint-in-v1": {"journal"},
    "tiny-habit-in-v1": {"need", "time_of_day"},
    "interest-activity-in-v1": {"interest_tag", "time_budget_minutes"},
}


class AllowedContext(_Frozen):
    """Exactly what the specialist model receives. Built only by ``policy.allowed_context``."""

    schema_id: InputSchema = Field(alias="schema")
    need: Need | None = None
    time_of_day: TimeOfDay | None = None
    interest_tag: InterestTag | None = None
    time_budget_minutes: TimeBudget | None = None
    journal: tuple[JournalExcerpt, ...] = Field(default=(), max_length=3)

    model_config = ConfigDict(extra="forbid", frozen=True, populate_by_name=True)

    @model_validator(mode="after")
    def only_declared_fields(self):
        allowed = _FIELDS[self.schema_id]
        present = {
            name for name in ("need", "time_of_day", "interest_tag", "time_budget_minutes")
            if getattr(self, name) is not None
        } | ({"journal"} if self.journal else set())
        if present - allowed:
            raise ValueError("field not allowed for this edge")
        required = allowed - {"journal"}
        if required - present:
            raise ValueError("missing field for this edge")
        if self.schema_id == "energy-hint-in-v1" and not self.journal:
            raise ValueError("energy hint requires authorized entries")
        return self

    def canonical(self) -> str:
        return json.dumps(self.model_dump(mode="json", by_alias=True), ensure_ascii=False,
                          sort_keys=True, separators=(",", ":"))

    def digest(self) -> str:
        return hashlib.sha256(self.canonical().encode()).hexdigest()

    def granted_entry_ids(self) -> frozenset[UUID]:
        return frozenset(item.entry_id for item in self.journal)


class DelegationRequest(_Frozen):
    """Coordinator → specialist runner. Never sent to a model as a whole."""

    collaboration_id: UUID
    edge: Edge
    rule_id: RuleId
    requester_bot: BotId
    specialist_bot: BotId
    primary_run_id: UUID
    specialist_run_id: UUID
    depth: Literal[1] = 1
    deadline_at: datetime
    allowed: AllowedContext


class EnergyHint(_Frozen):
    """Specialist output of ``nhip_energy_for_rure``: derived estimate, closed values only."""

    energy: Literal["low", "medium", "high", "unknown"]
    time_budget_minutes: TimeBudget
    basis: Literal["journal", "none"]
    source_entry_ids: tuple[UUID, ...] = Field(default=(), max_length=3)


class TinyHabit(_Frozen):
    """Specialist output of ``nhip_habit_for_may``: a generated suggestion."""

    habit_text: str = Field(min_length=10, max_length=200)
    duration_minutes: int = Field(ge=1, le=15)
    kind: HabitKind


class InterestActivity(_Frozen):
    """Specialist output of ``rure_activity_for_guong``: a generated suggestion."""

    activity_text: str = Field(min_length=10, max_length=240)
    challenge_kind: ChallengeKind


SpecialistOutput = EnergyHint | TinyHabit | InterestActivity


class SourceProvenance(_Frozen):
    source_kind: Literal["journal_entry"] = "journal_entry"
    source_id: UUID
    source_revision: int = Field(ge=1)
    local_date: date


class AuthorizationDecision(_Frozen):
    allowed: bool
    edge: Edge
    reason: DenyReason
    permission_version: int = Field(ge=0)
    data_version: int = Field(ge=0)


class ExecutionReceipt(_Frozen):
    """1-1 view of an ``ai_collaborations`` row. Content-free."""

    collaboration_id: UUID
    edge: Edge
    rule_id: RuleId
    status: Status
    primary_run_id: UUID
    specialist_run_id: UUID | None
    input_digest: str = Field(pattern=r"^[0-9a-f]{64}$")
    output_digest: str | None = Field(default=None, pattern=r"^[0-9a-f]{64}$")
    used_in_reply: bool
    started_at: datetime
    finished_at: datetime | None

    @classmethod
    def of(cls, row) -> "ExecutionReceipt":
        return cls(
            collaboration_id=row.id, edge=row.edge, rule_id=row.rule_id, status=row.status,
            primary_run_id=row.primary_run_id, specialist_run_id=row.specialist_run_id,
            input_digest=row.input_digest, output_digest=row.output_digest,
            used_in_reply=row.used_in_reply, started_at=row.started_at, finished_at=row.finished_at,
        )


class PrimaryBrief(_Frozen):
    """What the primary companion receives: an enum block for its instructions and/or one
    labelled data item. ``kind`` says whether it is a derived estimate or a generated suggestion."""

    kind: Literal["derived_estimate", "generated_suggestion"]
    instructions: str
    data_item: dict | None = None


def output_digest(output: BaseModel) -> str:
    canonical = json.dumps(output.model_dump(mode="json"), ensure_ascii=False, sort_keys=True,
                           separators=(",", ":"))
    return hashlib.sha256(canonical.encode()).hexdigest()
